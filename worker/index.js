import { SITE_URL } from '../src/config/site.js'
import { handleOrder } from './order.js'

/**
 * Тонкий шар перед статичними файлами сайту.
 *
 * Сам сайт — це готові файли з теки dist, і Cloudflare віддає їх сам.
 * Цей код потрібен для двох речей, які файлами не вирішуються:
 *
 *   1. www.syndicateclean.com → syndicateclean.com (301).
 *      Файл _redirects такого не вміє: він працює зі шляхами, але не з
 *      доменами (перевірено в документації Cloudflare). Без цього та сама
 *      сторінка живе за двома адресами, і посилання на сайт розповзаються
 *      у двох варіантах.
 *
 *   2. Заборона індексації на всіх адресах, крім основної. Сайт доступний
 *      ще й на технічних адресах Cloudflare — у пошуку їм робити нічого.
 *
 *   3. Приймання заявок з форми на /api/order — див. order.js.
 *
 * Адреса береться з SITE_URL у config/site.js, тобто з того самого місця,
 * що й canonical. Зміниться домен — цей код підхопить його сам.
 */

const CANONICAL_HOST = new URL(SITE_URL).hostname

export default {
  async fetch(request, env) {
    try {
      const url = new URL(request.url)

      // www → основний домен, зі збереженням шляху й параметрів.
      // Протокол проставляємо явно: редірект не має права відправити
      // людину на http, навіть якщо запит чомусь прийшов без шифрування.
      if (url.hostname === `www.${CANONICAL_HOST}`) {
        url.hostname = CANONICAL_HOST
        url.protocol = 'https:'
        return Response.redirect(url.toString(), 301)
      }

      // Заявка з форми. Перевіряємо до звернення до файлів: такої сторінки
      // на сайті немає, тож інакше запит впав би у 404.
      if (url.pathname === '/api/order') {
        return handleOrder(request, env)
      }

      let response = await env.ASSETS.fetch(request)

      // Сторінку 404 Cloudflare віддає з тим самим заголовком, що й решту
      // файлів: public, max-age=604800. Тобто браузер запам'ятовує, що
      // файлу немає, на цілий тиждень — і потім не питає повторно.
      //
      // Для сайту, куди фото докладають поступово, це пастка: поки знімка
      // не було, кожен відвідувач закешував 404; кладеш файл на місце — а
      // ті, хто вже заходив, ще сім днів бачать порожнє місце замість фото.
      // Саме так сталося з /services/carpet.webp.
      //
      // Відсутність файлу — стан тимчасовий, і кешувати його не можна.
      // Сама сторінка 404 від цього не постраждає: вона легка й генерується
      // з готового файлу.
      if (response.status === 404) {
        response = new Response(response.body, response)
        response.headers.set('Cache-Control', 'no-store')
      }

      // Те саме «памʼятай тиждень» ламало й заміну картинок.
      //
      // Файли бувають двох сортів, і кешувати їх однаково не можна:
      //
      //   /assets/* — збірка Vite. В імені кожного файлу стоїть хеш вмісту,
      //     тож змінився файл — змінилось імʼя. Такі можна тримати в кеші
      //     скільки завгодно: браузер ніколи не отримає під тим імʼям щось
      //     інше. Їх не чіпаємо.
      //
      //   решта — фото, які кладуть руками: /services, /chemistry, /hero.
      //     Тут імʼя стале (sofa.webp), а вміст змінюється — саме так
      //     задумано, щоб власник міг покласти свій знімок замість стокового.
      //     З семиденним кешем без ревалідації заміна не доходила до тих,
      //     хто вже бував на сайті: вони цілий тиждень бачили старе фото,
      //     і зрозуміти це збоку неможливо — сайт же «оновлений».
      //
      // must-revalidate: годину файл лежить у кеші як є, далі браузер
      // перепитує. Якщо файл не змінився — сервер відповідає 304 без тіла,
      // тобто це не зайвий трафік, а лише коротке «те саме».
      //
      // Сторінки сюди не потрапляють навмисно: у них уже стоїть max-age=0,
      // тобто браузер перепитує щоразу, і правка тексту видно одразу.
      // Година затримки для тексту сайту була б кроком назад.
      const isPage = (response.headers.get('content-type') || '').includes('text/html')

      if (response.ok && !isPage && !url.pathname.startsWith('/assets/')) {
        response = new Response(response.body, response)
        response.headers.set('Cache-Control', 'public, max-age=3600, must-revalidate')
      }

      // Будь-яка адреса, крім основної (технічні домени Cloudflare,
      // прев'ю-версії) — закрита від пошукових систем.
      if (url.hostname !== CANONICAL_HOST) {
        const copy = new Response(response.body, response)
        copy.headers.set('X-Robots-Tag', 'noindex')
        return copy
      }

      return response
    } catch {
      // Що б тут не зламалось, сайт має лишитись доступним:
      // віддаємо файли напряму, без жодної обробки.
      return env.ASSETS.fetch(request)
    }
  },
}
