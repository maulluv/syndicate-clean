/**
 * Крихітний спільний сигнал: «унизу екрана вже є явна кнопка дії».
 *
 * Потрібен, бо калькулятор і плаваюча кнопка звʼязку живуть у різних гілках
 * дерева — кнопка в layout, калькулятор усередині сторінки — і передати щось
 * пропсами між ними неможливо без стану на весь застосунок. Заводити для
 * одного прапорця контекст чи бібліотеку — надто дорого.
 *
 * Чому не CSS-позначка на <body>: так поведінка розʼїжджається між двома
 * файлами стилів, і зрозуміти, чому кнопка сховалась, стає важко. Тут усе
 * рішення видно в самому компоненті.
 */

let active = false
const listeners = new Set()

/** Повідомити, що липка кнопка дії зʼявилась або зникла. */
export function setStickyCta(next) {
  if (active === next) return
  active = next
  listeners.forEach((listener) => listener(active))
}

/** Підписатись. Одразу віддає поточний стан; повертає функцію відписки. */
export function subscribeStickyCta(listener) {
  listeners.add(listener)
  listener(active)
  return () => listeners.delete(listener)
}
